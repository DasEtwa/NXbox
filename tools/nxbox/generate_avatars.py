#!/usr/bin/env python3
"""Regenerate embedded NXbox JPEG avatars (requires Pillow 12.3.0)."""

from io import BytesIO
from pathlib import Path
import colorsys
from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parents[2]


def jpeg(image):
    output = BytesIO()
    image.save(output, "JPEG", quality=90, subsampling=0, optimize=False)
    return output.getvalue()


def generate():
    logo = Image.open(ROOT / "dist/nxbox/Assets/Square150x150Logo.png").convert("RGBA")
    logo = ImageOps.contain(logo, (256, 256), Image.Resampling.LANCZOS)
    default = Image.new("RGB", (256, 256), "black")
    default.paste(logo, ((256 - logo.width) // 2, (256 - logo.height) // 2), logo)
    images = [("NXBOX_ACCOUNT_JPEG", jpeg(default))]
    for index in range(20):
        # Four original geometric emblems, each in five identity colors. Supersample edges.
        rgb = tuple(round(c * 255) for c in colorsys.hsv_to_rgb((index % 5) / 5, 0.65, 0.72))
        image = Image.new("RGB", (768, 768), rgb)
        draw = ImageDraw.Draw(image)
        draw.ellipse((96, 96, 672, 672), fill=tuple(min(c + 35, 255) for c in rgb))
        if index // 5 == 0:
            draw.polygon([(384, 180), (570, 384), (384, 588), (198, 384)], fill="white")
        elif index // 5 == 1:
            draw.ellipse((225, 225, 543, 543), outline="white", width=66)
        elif index // 5 == 2:
            draw.rounded_rectangle((225, 225, 543, 543), radius=60, fill="white")
            draw.rectangle((330, 150, 438, 618), fill=rgb)
        else:
            draw.polygon([(180, 498), (300, 252), (384, 408), (468, 252), (588, 498)], fill="white")
        images.append(
            (f"NXBOX_PRESET_{index}", jpeg(image.resize((256, 256), Image.Resampling.LANCZOS)))
        )
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Generated by tools/nxbox/generate_avatars.py. Do not edit.",
        "// clang-format off",
        "#pragma once",
        "#include <array>",
        "#include <span>",
        '#include "common/common_types.h"',
        "namespace Core::Constants {",
    ]
    for name, data in images:
        lines.append(f"inline constexpr std::array<u8, {len(data)}> {name} = {{")
        lines.extend(
            "    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ","
            for i in range(0, len(data), 16)
        )
        lines.append("};")
    lines.append("inline constexpr std::array<std::span<const u8>, 20> NXBOX_PRESET_AVATARS = {")
    lines.extend(f"    NXBOX_PRESET_{i}," for i in range(20))
    lines.extend(["};", "} // namespace Core::Constants", "// clang-format on", ""])
    (ROOT / "src/core/constants_nxbox.h").write_text("\n".join(lines))


if __name__ == "__main__":
    generate()
